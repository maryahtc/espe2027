  check('Simulação: navegação e volta ao caso', (await sim.locator('[data-voltar-caso]').getAttribute('href')) === `/casos/${simCase}#planejamento`)
  check('Simulação: zero escrita no banco e no Storage', fingerprint(true) === FPs)
  // O rascunho mudou só por causa do caso/plano simulados; ver workflows não acrescenta nada ao cookie.
  const size1 = await cookieSize()
  await go(sim, '/workflows')
  await go(sim, `${WF}/prova`)
  check('Simulação: navegar pelos workflows não aumenta o cookie cifrado', (await cookieSize()) === size1 && size0 > 0)

