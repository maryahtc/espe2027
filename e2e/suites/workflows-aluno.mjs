  const simLink = await sim.locator('[data-consultar-workflow]').getAttribute('href')
  check('Simulação: "Consultar workflow" no plano do rascunho abre a etapa ligada', simLink === `${WF}/cimentacao?caso=${simCase}`, simLink)
